'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'site-config.js'), 'utf8'), context);
const c = context.window.FOGATA, v = c.verified || {};
const data = { '@context': 'https://schema.org', '@type': 'Restaurant', name: c.name, servesCuisine: 'Mexican' };
if (v.phone) data.telephone = '+1' + c.phone.replace(/\D/g, '');
if (v.address) data.address = { '@type': 'PostalAddress', streetAddress: c.address.street, addressLocality: c.address.city, addressRegion: c.address.state, postalCode: c.address.zip, addressCountry: 'US' };
const dayNames = { mon:'Monday', tue:'Tuesday', wed:'Wednesday', thu:'Thursday', fri:'Friday', sat:'Saturday', sun:'Sunday' };
if (v.hours) data.openingHoursSpecification = Object.entries(c.hours).filter(([,h]) => h && h.open && h.close).map(([day,h]) => ({ '@type':'OpeningHoursSpecification', dayOfWeek: dayNames[day], opens:h.open, closes:h.close }));
if (v.social) data.sameAs = Object.values(c.social).filter(Boolean);
const file = path.join(__dirname, 'index.html');
let html = fs.readFileSync(file, 'utf8');
html = html.replace(/<script id="business-data" type="application\/ld\+json">[\s\S]*?<\/script>/, '<script id="business-data" type="application/ld+json">\n' + JSON.stringify(data, null, 2).replace(/</g, '\\u003c') + '\n</script>');
html = html.replace(/<meta name="robots" content="[^"]*">/, '<meta name="robots" content="' + (c.launchApproved ? 'index, follow' : 'noindex, nofollow') + '">');
fs.writeFileSync(file, html);
console.log('Verified metadata generated.');
